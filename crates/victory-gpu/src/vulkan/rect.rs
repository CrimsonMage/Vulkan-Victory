//! The console's rectangle lists (topology 17) on Vulkan: a geometry stage
//! behind the vertex program completes each rectangle, as the D3D12 path's
//! `rect_list_gs` does. A rectangle comes as three corners of a
//! screen-aligned rectangle; the corner between the other two is the vertex
//! that shares x with one and y with the other, and the fourth vertex lies
//! opposite it (`a + b - corner`, for the position and every output). Both
//! triangles start with the first vertex (flat values are its own, the
//! provoking vertex), in the input's winding. Three vertices that differ in
//! w or are no such corners stay their triangle. The title clears its UI
//! plane with such a rectangle each frame (`VS_Blit`).
//!
//! The vertex outputs are vec4s at the title's semantic locations (ABI v2
//! section 6: 0..30, from the registry); the stage passes all of them
//! through (unwritten ones are undefined, as a pixel input no vertex
//! writes): 31 vec4s and the position, 128 components, NVIDIA's limit.
//!
//! Compiled offline with `glslc -x hlsl -fshader-stage=geom
//! --target-env=vulkan1.3 -Os` from this HLSL, the members `aN` written
//! out for every N in 0..=30, and `fourth` likewise per member:
//!
//! ```hlsl
//! struct V {
//!     float4 pos : SV_Position;
//!     [[vk::location(N)]] float4 aN : AN;   // N = 0..30
//! };
//! V fourth(V a, V b, V c) {
//!     V d;
//!     d.pos = a.pos + b.pos - c.pos;
//!     d.aN = a.aN + b.aN - c.aN;            // each N
//!     return d;
//! }
//! bool corner(float4 c, float4 a, float4 b) {
//!     return (c.x == a.x && c.y == b.y) || (c.x == b.x && c.y == a.y);
//! }
//! [maxvertexcount(6)]
//! void main(triangle V v[3], inout TriangleStream<V> s) {
//!     int c = -1;
//!     if (v[0].pos.w == v[1].pos.w && v[1].pos.w == v[2].pos.w && v[0].pos.w > 0) {
//!         for (int i = 0; i < 3; i++) {
//!             if (c < 0 && corner(v[i].pos, v[(i + 1) % 3].pos, v[(i + 2) % 3].pos)) {
//!                 c = i;
//!             }
//!         }
//!     }
//!     if (c < 0) {
//!         [loop] for (int k = 0; k < 3; k++) {
//!             s.Append(v[k]);
//!         }
//!         return;
//!     }
//!     int n1 = (c + 1) % 3;
//!     int n2 = (c + 2) % 3;
//!     V q[4];
//!     q[0] = v[c];
//!     q[1] = v[n1];
//!     q[2] = fourth(v[n1], v[n2], v[c]);
//!     q[3] = v[n2];
//!     int r = c == 0 ? 0 : (c == 2 ? 1 : 3);
//!     [loop] for (int k = 0; k < 6; k++) {
//!         if (k == 3) {
//!             s.RestartStrip();
//!         }
//!         int at = k == 0 || k == 3 ? 0 : (k == 1 ? 1 : (k == 2 || k == 4 ? 2 : 3));
//!         s.Append(q[(r + at) % 4]);
//!     }
//! }
//! ```

