/// The geometry module, made once; `None` without `geometryShader`.
pub(super) fn module(b: &Backend) -> Option<vk::ShaderModule> {
    static MODULE: OnceLock<Option<vk::ShaderModule>> = OnceLock::new();
    *MODULE.get_or_init(|| {
        if b.host.caps.core.geometry_shader != vk::TRUE {
            tracing::warn!("Vulkan: no geometryShader; rectangle lists are not drawn");
            return None;
        }
        // SAFETY: valid SPIR-V words (spirv-val, vulkan1.3).
        unsafe { b.host.device.create_shader_module(&vk::ShaderModuleCreateInfo::default().code(WORDS), None) }.ok()
    })
}

