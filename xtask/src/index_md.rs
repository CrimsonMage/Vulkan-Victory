//! The translation index as markdown: summary, opcode coverage,
//! approximations, refused and invalid programs. Rows are sorted by name or
//! count, never by time, so an unchanged translator and pack give an
//! unchanged file.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use victory_shader::HwStage;

use crate::index::{Origin, Outcome, Program};

/// The stage column, in table order.
const STAGES: [&str; 7] = [
    "vertex", "pixel", "compute", "mesh", "geometry", "hull", "none",
];

fn stage_name(stage: Option<HwStage>) -> &'static str {
    match stage {
        Some(HwStage::Vs) => "vertex",
        Some(HwStage::Ps) => "pixel",
        Some(HwStage::Cs) => "compute",
        Some(HwStage::Ms) => "mesh",
        // merged stages on GFX10: ES with GS, LS with HS
        Some(HwStage::Es | HwStage::Gs) => "geometry",
        Some(HwStage::Ls | HwStage::Hs) => "hull",
        None => "none",
    }
}

/// One opcode across the pack.
#[derive(Default)]
struct OpStat {
    programs: usize,
    translated: usize,
    /// Refusals at this opcode, by reason.
    refused: BTreeMap<String, usize>,
    /// Translated programs that took an approximation here, by note.
    approx: BTreeMap<&'static str, usize>,
}

impl OpStat {
    fn status(&self) -> &'static str {
        let refused = !self.refused.is_empty();
        match () {
            _ if refused && self.translated == 0 => "unsupported",
            _ if refused => "partly unsupported",
            _ if !self.approx.is_empty() => "approximated",
            _ if self.translated > 0 => "handled",
            _ => "not reached (only in refused programs)",
        }
    }

    fn notes(&self) -> String {
        let refused = self
            .refused
            .iter()
            .map(|(r, n)| format!("refused ({n}): {r}"));
        let approx = self
            .approx
            .iter()
            .map(|(a, n)| format!("approximated ({n}): {a}"));
        refused.chain(approx).collect::<Vec<_>>().join("; ")
    }
}

pub fn render(origin: &Origin, programs: &[Program], known: &[&'static str]) -> String {
    let mut s = String::new();
    header(&mut s, origin);
    summary(&mut s, origin, programs);
    let ops = coverage(programs);
    coverage_table(&mut s, &ops);
    not_seen(&mut s, &ops, known);
    approximations(&mut s, programs);
    refused(&mut s, programs);
    invalid(&mut s, programs);
    s
}

fn header(s: &mut String, o: &Origin) {
    let _ = writeln!(s, "# Translation index\n");
    let _ = writeln!(
        s,
        "Every shader container of a title's dump through the SPIR-V translator \
         (`crates/victory-shader/src/vk/`), generated by \
         `cargo xtask translation-index --pack <pack>`; do not edit by hand.\n"
    );
    let _ = writeln!(
        s,
        "- Commit: `{}` (translator fingerprint `{}`)",
        o.commit, o.translator
    );
    let _ = writeln!(
        s,
        "- Pack: `{}` ({} bytes, blake3 `{}`)",
        o.pack, o.bytes, o.pack_hash
    );
    let val = if o.validated {
        "every module through `spirv-val --target-env vulkan1.3 --scalar-block-layout`"
    } else {
        "not run (`spirv-val` not on PATH)"
    };
    let _ = writeln!(s, "- Validation: {val}\n");
    let _ = writeln!(
        s,
        "Programs are distinct containers, named by the first 16 hex digits of their \
         blake3 (as a run's log names them) and by their record's name.\n"
    );
}

fn summary(s: &mut String, o: &Origin, programs: &[Program]) {
    let translated = programs
        .iter()
        .filter(|p| matches!(p.outcome, Outcome::Translated { .. }))
        .count();
    let invalid = programs.iter().filter(|p| invalid_of(p).is_some()).count();
    let approx = programs.iter().filter(|p| !approx_of(p).is_empty()).count();
    let _ = writeln!(s, "## Summary\n");
    let _ = writeln!(s, "| | Programs |\n|---|---:|");
    let _ = writeln!(s, "| Containers | {} |", programs.len());
    let _ = writeln!(s, "| Translated | {translated} |");
    let _ = writeln!(s, "| … with approximations | {approx} |");
    let _ = writeln!(
        s,
        "| … invalid (spirv-val) | {} |",
        if o.validated {
            invalid.to_string()
        } else {
            "not run".into()
        }
    );
    let _ = writeln!(s, "| Refused | {} |", programs.len() - translated);
    let _ = writeln!(s, "| Corrupt records (not counted) | {} |\n", o.corrupt);
    stage_table(s, programs);
    let reasons = counts(
        programs
            .iter()
            .filter_map(refusal)
            .map(|(r, _)| r.to_owned()),
    );
    let _ = writeln!(s, "### Refused, by reason\n");
    count_table(s, "Reason", &reasons);
    if o.validated && invalid > 0 {
        let first = counts(programs.iter().filter_map(invalid_of).map(digits_out));
        let _ = writeln!(s, "### Invalid, by spirv-val's first complaint\n");
        count_table(s, "Complaint", &first);
    }
}

fn stage_table(s: &mut String, programs: &[Program]) {
    let _ = writeln!(
        s,
        "| Stage | Containers | Translated | With approximations | Invalid | Refused |"
    );
    let _ = writeln!(s, "|---|---:|---:|---:|---:|---:|");
    for stage in STAGES {
        let of: Vec<&Program> = programs
            .iter()
            .filter(|p| stage_name(p.stage) == stage)
            .collect();
        if of.is_empty() {
            continue;
        }
        let ok = of
            .iter()
            .filter(|p| matches!(p.outcome, Outcome::Translated { .. }))
            .count();
        let approx = of.iter().filter(|p| !approx_of(p).is_empty()).count();
        let bad = of.iter().filter(|p| invalid_of(p).is_some()).count();
        let _ = writeln!(
            s,
            "| {stage} | {} | {ok} | {approx} | {bad} | {} |",
            of.len(),
            of.len() - ok
        );
    }
    s.push('\n');
}

/// Values counted, most first (then by value).
fn counts(items: impl Iterator<Item = String>) -> Vec<(String, usize)> {
    let mut m: BTreeMap<String, usize> = BTreeMap::new();
    for i in items {
        *m.entry(i).or_default() += 1;
    }
    let mut v: Vec<(String, usize)> = m.into_iter().collect();
    v.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    v
}

fn count_table(s: &mut String, what: &str, rows: &[(String, usize)]) {
    if rows.is_empty() {
        let _ = writeln!(s, "None.\n");
        return;
    }
    let _ = writeln!(s, "| {what} | Programs |\n|---|---:|");
    for (r, n) in rows {
        let _ = writeln!(s, "| {} | {n} |", cell(r));
    }
    s.push('\n');
}

fn coverage(programs: &[Program]) -> BTreeMap<&'static str, OpStat> {
    let mut ops: BTreeMap<&'static str, OpStat> = BTreeMap::new();
    for p in programs {
        let ok = matches!(p.outcome, Outcome::Translated { .. });
        for &op in &p.opcodes {
            let st = ops.entry(op).or_default();
            st.programs += 1;
            st.translated += usize::from(ok);
        }
        if let Some((reason, Some(at))) = refusal(p) {
            *ops.entry(at)
                .or_default()
                .refused
                .entry(reason.to_owned())
                .or_default() += 1;
        }
        for a in approx_of(p).iter().filter(|a| !a.opcode.is_empty()) {
            *ops.entry(a.opcode)
                .or_default()
                .approx
                .entry(a.note)
                .or_default() += 1;
        }
    }
    ops
}

fn coverage_table(s: &mut String, ops: &BTreeMap<&'static str, OpStat>) {
    let _ = writeln!(s, "## Instruction coverage\n");
    let _ = writeln!(
        s,
        "Every opcode the pack's programs use. Status: *handled* (in translated programs, \
         no approximation), *approximated* (a translation took an approximation at it), \
         *partly unsupported* / *unsupported* (some / every program using it that reached \
         it was refused there), *not reached* (it appears only in programs refused \
         elsewhere). Programs: those using the opcode; translated: of those, translated.\n"
    );
    let mut by_status: BTreeMap<&str, usize> = BTreeMap::new();
    for st in ops.values() {
        *by_status.entry(st.status()).or_default() += 1;
    }
    let tally: Vec<String> = by_status.iter().map(|(k, n)| format!("{n} {k}")).collect();
    let _ = writeln!(s, "{} opcodes: {}.\n", ops.len(), tally.join(", "));
    let _ = writeln!(
        s,
        "| Opcode | Programs | Translated | Status | Notes |\n|---|---:|---:|---|---|"
    );
    for (op, st) in ops {
        let _ = writeln!(
            s,
            "| `{op}` | {} | {} | {} | {} |",
            st.programs,
            st.translated,
            st.status(),
            cell(&st.notes())
        );
    }
    s.push('\n');
}

fn not_seen(s: &mut String, ops: &BTreeMap<&'static str, OpStat>, known: &[&'static str]) {
    let unused: Vec<&str> = known
        .iter()
        .copied()
        .filter(|k| !ops.contains_key(k))
        .collect();
    let _ = writeln!(
        s,
        "Not seen ({} opcodes the decoder knows, no program uses): {}\n",
        unused.len(),
        unused.join(", ")
    );
}

fn approximations(s: &mut String, programs: &[Program]) {
    let mut notes: BTreeMap<&str, (usize, BTreeMap<&str, usize>)> = BTreeMap::new();
    for p in programs {
        let approx = approx_of(p);
        for note in approx.iter().map(|a| a.note).collect::<BTreeSet<_>>() {
            notes.entry(note).or_default().0 += 1;
        }
        for a in approx {
            *notes
                .entry(a.note)
                .or_default()
                .1
                .entry(a.opcode)
                .or_default() += 1;
        }
    }
    let _ = writeln!(s, "## Approximations\n");
    let _ = writeln!(
        s,
        "Where a translated program differs from the console (`docs/vulkan-abi.md` section 9). \
         At: the instruction being lifted when the approximation was taken (for a value made \
         on first use, the instruction that reads it).\n"
    );
    if notes.is_empty() {
        let _ = writeln!(s, "None.\n");
        return;
    }
    let mut rows: Vec<_> = notes.into_iter().collect();
    rows.sort_by(|a, b| b.1.0.cmp(&a.1.0).then_with(|| a.0.cmp(b.0)));
    let _ = writeln!(
        s,
        "| Approximation | Programs | At (programs) |\n|---|---:|---|"
    );
    for (note, (n, at)) in rows {
        let at: Vec<String> = at
            .iter()
            .map(|(op, k)| format!("`{}` ({k})", if op.is_empty() { "?" } else { op }))
            .collect();
        let _ = writeln!(s, "| {} | {n} | {} |", cell(note), at.join(", "));
    }
    s.push('\n');
}

fn refused(s: &mut String, programs: &[Program]) {
    let mut rows: Vec<(&str, &Program)> = programs
        .iter()
        .filter_map(|p| refusal(p).map(|(r, _)| (r, p)))
        .collect();
    rows.sort_by(|a, b| a.0.cmp(b.0).then_with(|| a.1.hash.cmp(&b.1.hash)));
    let _ = writeln!(s, "## Refused programs\n");
    if rows.is_empty() {
        let _ = writeln!(s, "None.\n");
        return;
    }
    let _ = writeln!(s, "| Hash | Name | Stage | Reason |\n|---|---|---|---|");
    for (reason, p) in rows {
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} |",
            p.hash,
            cell(&p.name),
            stage_name(p.stage),
            cell(reason)
        );
    }
    s.push('\n');
}

fn invalid(s: &mut String, programs: &[Program]) {
    let rows: Vec<(&str, &Program)> = programs
        .iter()
        .filter_map(|p| invalid_of(p).map(|l| (l, p)))
        .collect();
    if rows.is_empty() {
        return;
    }
    let _ = writeln!(s, "## Invalid programs (spirv-val)\n");
    let _ = writeln!(
        s,
        "| Hash | Name | Stage | First complaint |\n|---|---|---|---|"
    );
    for (line, p) in rows {
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} |",
            p.hash,
            cell(&p.name),
            stage_name(p.stage),
            cell(line)
        );
    }
    s.push('\n');
}

fn refusal(p: &Program) -> Option<(&str, Option<&'static str>)> {
    match &p.outcome {
        Outcome::Refused { reason, at } => Some((reason.as_str(), *at)),
        Outcome::Translated { .. } => None,
    }
}

fn approx_of(p: &Program) -> &[victory_shader::vk::Approx] {
    match &p.outcome {
        Outcome::Translated { approx, .. } => approx,
        Outcome::Refused { .. } => &[],
    }
}

fn invalid_of(p: &Program) -> Option<&str> {
    match &p.outcome {
        Outcome::Translated { invalid, .. } => invalid.as_deref(),
        Outcome::Refused { .. } => None,
    }
}

/// A complaint with its ids and numbers as `N`, so equal complaints group.
fn digits_out(line: &str) -> String {
    let mut out = String::with_capacity(line.len());
    let mut digit = false;
    for c in line.chars() {
        if !c.is_ascii_digit() {
            out.push(c);
        } else if !digit {
            out.push('N');
        }
        digit = c.is_ascii_digit();
    }
    out
}

/// Text safe inside a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn complaints_group_and_statuses_read_right() {
        assert_eq!(
            digits_out("error: line 12: Operand 3 of %45"),
            "error: line N: Operand N of %N"
        );
        let mut st = OpStat {
            programs: 3,
            translated: 2,
            ..OpStat::default()
        };
        assert_eq!(st.status(), "handled");
        st.approx.insert("a note", 1);
        assert_eq!(st.status(), "approximated");
        st.refused.insert("x is not supported".into(), 1);
        assert_eq!(st.status(), "partly unsupported");
        st.translated = 0;
        assert_eq!(st.status(), "unsupported");
        assert_eq!(cell("a|b"), "a\\|b");
    }
}
